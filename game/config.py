# ── Helper ─────────────────────────────────────────────────────────────
def get_ending(route: str, ap: int, tp: int) -> dict:
    pool = ENDINGS.get(route, ENDINGS["COLD"])
    for e in pool:
        if ap >= e['min_ap'] and tp >= e['min_tp']:
            return e
    return pool[-1]


